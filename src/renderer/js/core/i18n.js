/** 取值：t('textCompare.openLeft')；缺失时回退中文，再缺失回退键名。 */
export function translate(lang, key, params) {
  const path = String(key).split('.');
  const lookup = (table) => path.reduce((acc, part) => (acc == null ? undefined : acc[part]), table);
  let value = lookup(DICT[lang]);
  if (value === undefined) value = lookup(DICT['zh-CN']);
  if (value === undefined) return key;
  if (!params) return value;
  return String(value).replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m,
  );
}

export function createTranslator(getLang) {
  return (key, params) => translate(getLang(), key, params);
}

/** 把嵌套字典压平成 'module.key' -> 文本，便于校验两种语言的键是否一一对应。 */
function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v !== null && typeof v === 'object') flatten(v, key, out);
    else out[key] = v;
  }
  return out;
}

export const DICT_ZH = flatten(DICT['zh-CN']);
export const DICT_EN = flatten(DICT.en);
